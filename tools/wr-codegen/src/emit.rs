//! Writes the schema as Rust source (static tables) and a JSON summary.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use serde::Serialize;

use crate::rules::{self, Builder, Codec, Def};

fn codec_src(c: &Codec) -> String {
    match c {
        Codec::Bool => "C::Bool".into(),
        Codec::Int { bits, signed } => format!("C::Int {{ bits: {bits}, signed: {signed} }}"),
        Codec::F32 => "C::F32".into(),
        Codec::F64 => "C::F64".into(),
        Codec::Char => "C::Char".into(),
        Codec::Str => "C::Str".into(),
        Codec::Decimal => "C::Decimal".into(),
        Codec::Enum(i) => format!("C::Enum({i})"),
        Codec::Object(i) => format!("C::Object({i})"),
        Codec::BpRef { target, class } => {
            format!("C::BpRef {{ target: {target}, class: {class} }}")
        }
        Codec::WeakLink(i) => format!("C::WeakLink({i})"),
        Codec::SharedString => "C::SharedString".into(),
        Codec::Asset(n) => format!("C::Asset({n:?})"),
        Codec::Unity(k) => format!("C::Unity(U::{k:?})"),
        Codec::Overrides => "C::Overrides".into(),
        Codec::PrototypeLink => "C::PrototypeLink".into(),
        Codec::BlueprintGuid => "C::BlueprintGuid".into(),
        Codec::Seq { list, elem } => {
            format!("C::Seq {{ list: {list}, elem: &{} }}", codec_src(elem))
        }
        Codec::Unsupported(why) => format!("C::Unsupported({why:?})"),
    }
}

fn def_src(d: &Def) -> String {
    match d {
        Def::Zero => "D::Zero".into(),
        Def::Null => "D::Null".into(),
        Def::Bool(b) => format!("D::Bool({b})"),
        Def::Int(i) => format!("D::Int({i})"),
        Def::Float(f) if f.is_infinite() => {
            if *f > 0.0 {
                "D::Float(f64::INFINITY)".into()
            } else {
                "D::Float(f64::NEG_INFINITY)".into()
            }
        }
        Def::Float(f) => format!("D::Float({f:?})"),
        Def::EmptyStr => "D::EmptyStr".into(),
        Def::NonEmptyStr => "D::NonEmptyStr".into(),
        Def::NewObject => "D::NewObject".into(),
        Def::Floats(v) => {
            format!(
                "D::Floats(&[{}])",
                v.iter().map(|x| format!("{x:?}")).collect::<Vec<_>>().join(", ")
            )
        }
        Def::EmptySeq => "D::EmptySeq".into(),
        Def::Unknown(_) => "D::Unknown".into(),
    }
}

/// The generated module. Deterministic: same input, same bytes.
#[must_use]
pub fn emit(b: &Builder<'_>) -> String {
    let mut s = String::new();
    s.push_str(
        "// @generated by tools/wr-codegen from the game's decompiled declarations.\n\
         // Types, fields, enums and TypeIds only: no game data. Don't edit by hand;\n\
         // rerun `cargo run -p wr-codegen -- gen`.\n\n\
         use crate::schema::{Codec as C, Def as D, EnumDef, Field, TypeDef, UnityKind as U};\n\n",
    );
    let _ = writeln!(s, "pub static TYPES: [TypeDef; {}] = [", b.types.len());
    for (i, t) in b.types.iter().enumerate() {
        let guid = t.guid.as_deref().map_or_else(|| "0".to_owned(), |g| format!("0x{g}"));
        let base = t.base.map_or_else(|| "u32::MAX".to_owned(), |x| x.to_string());
        let _ = writeln!(s, "    // {i}");
        let _ = writeln!(
            s,
            "    TypeDef {{ name: {:?}, short: {:?}, guid: {guid}, flags: {:#x}, base: {base}, hooks: {:#x}, runtime_fields: {}, fact_hooks: {:#x}, handlers: &{:?}, fields: &[",
            t.name,
            t.short,
            t.flags,
            t.hooks,
            t.runtime_fields.len(),
            t.fact_hooks,
            t.handlers
        );
        for f in &t.fields {
            let _ = writeln!(
                s,
                "        Field {{ name: {:?}, json: {:?}, codec: {}, flags: {:#x}, default: {}, declared_in: {} }},",
                f.name,
                f.json,
                codec_src(&f.codec),
                f.flags,
                def_src(&f.default),
                f.declared_in
            );
        }
        s.push_str("    ] },\n");
    }
    s.push_str("];\n\n");
    let _ = writeln!(s, "pub static ENUMS: [EnumDef; {}] = [", b.enums.len());
    for e in &b.enums {
        let members: Vec<String> = e.members.iter().map(|(n, v)| format!("({n:?}, {v})")).collect();
        let _ = writeln!(
            s,
            "    EnumDef {{ name: {:?}, bits: {}, signed: {}, flags: {}, members: &[{}] }},",
            e.name,
            e.bits,
            e.signed,
            e.flags,
            members.join(", ")
        );
    }
    s.push_str("];\n\n");
    let mut ids: Vec<(u128, usize)> = b
        .types
        .iter()
        .enumerate()
        .filter_map(|(i, t)| {
            t.guid.as_deref().and_then(|g| u128::from_str_radix(g, 16).ok()).map(|g| (g, i))
        })
        .collect();
    ids.sort_unstable();
    ids.dedup_by_key(|x| x.0);
    s.push_str(
        "/// `[TypeId]` GUID (as written, read as one big-endian hex number) → type, sorted.\n",
    );
    let _ = writeln!(s, "pub static TYPE_IDS: [(u128, u32); {}] = [", ids.len());
    for (g, i) in ids {
        let _ = writeln!(s, "    ({g:#034x}, {i}),");
    }
    s.push_str("];\n");
    // FNV-1a of everything above: packs store it and refuse a different schema.
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for b in s.bytes() {
        h = (h ^ u64::from(b)).wrapping_mul(0x0100_0000_01b3);
    }
    let _ = writeln!(
        s,
        "\n/// Hash of this file's tables; content packs record it.\npub const FINGERPRINT: u64 = {h:#018x};"
    );
    s
}

#[derive(Serialize)]
pub struct Summary<'a> {
    pub types: usize,
    pub enums: usize,
    pub type_ids: usize,
    pub decodable: usize,
    pub unsupported_field_types: usize,
    pub problems: &'a rules::Problems,
    /// Type → hooks with the declaring type, for types with any hook.
    pub hooks: BTreeMap<&'a str, &'a BTreeMap<String, String>>,
    /// Type → runtime (non-serialized) instance fields, for `[TypeId]` types.
    pub runtime_fields: BTreeMap<&'a str, &'a [String]>,
    pub enums_with_unresolved_members: Vec<&'a str>,
    /// Files tree-sitter couldn't parse cleanly (`file:line` of the first error).
    pub syntax_error_files: Vec<String>,
}

#[must_use]
pub fn summary<'a>(b: &'a Builder<'_>) -> Summary<'a> {
    Summary {
        types: b.types.len(),
        enums: b.enums.len(),
        type_ids: b.types.iter().filter(|t| t.guid.is_some()).count(),
        decodable: b.types.iter().filter(|t| t.flags & rules::T_NOT_DECODABLE == 0).count(),
        unsupported_field_types: b.problems.unsupported.len(),
        problems: &b.problems,
        hooks: b
            .types
            .iter()
            .filter(|t| !t.hook_sources.is_empty())
            .map(|t| (t.name.as_str(), &t.hook_sources))
            .collect(),
        runtime_fields: b
            .types
            .iter()
            .filter(|t| t.guid.is_some() && !t.runtime_fields.is_empty())
            .map(|t| (t.name.as_str(), t.runtime_fields.as_slice()))
            .collect(),
        enums_with_unresolved_members: b
            .enums
            .iter()
            .filter(|e| !e.unresolved.is_empty())
            .map(|e| e.name.as_str())
            .collect(),
        syntax_error_files: Vec::new(),
    }
}
