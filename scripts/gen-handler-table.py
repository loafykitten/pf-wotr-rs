#!/usr/bin/env python3
"""Generates crates/wr-sim/src/combat/replay/handler_table.rs from the decompiled game code.

Which classes may appear as a rule's singleton handler (an `h` record without a fact or component):
- every class implementing `IGlobalRulebookHandler<T>` (the event bus' global subscribers) that is not a
  fact's component (those are dispatched with their fact and component, another kind of record), and
- every fact or part class (derived from `UnitFact`/`EntityFact`/`UnitPart`/`EntityPart`) implementing `IInitiatorRulebookHandler<T>` or
  `ITargetRulebookHandler<T>` (`ActivatableAbility`, `UnitPartFavoredEnemy`: the fact or part is the handler itself, no component),
for each rule X that is T or derives from T (the handler interfaces are contravariant: `in T`, so a
`RulebookTargetEvent` handler handles all its descendants).

Reads decompiled/Assembly-CSharp (class declarations only: names and their bases), writes names.
Usage: python3 -I scripts/gen-handler-table.py   (from the repository root)
"""
import re, sys, pathlib, collections

root = pathlib.Path("decompiled/Assembly-CSharp")
decl = re.compile(r"^\s*(?:public |internal |private |protected |sealed |abstract |static |partial )*(class|interface|struct)\s+(\w+)(?:<[^>{]*>)?\s*(?::\s*([^{]*?))?\s*(?:where [^{]*)?\{?\s*$")
nested_names = {}  # nested type name -> Outer+Inner
bases = {}      # type name -> list of base names (generics stripped)
ns_of = {}      # type name -> namespace (the directory)
kind = {}
for f in root.glob("*/*.cs"):
    ns = f.parent.name
    outer = None
    for line in f.read_text(errors="replace").splitlines():
        top = line.startswith(("public ", "internal "))
        # a type nested one level in the file's top-level type (the oracle names it `Outer+Inner`)
        nested = outer is not None and re.match(r"^\t(public|internal|private|protected)\s", line) is not None
        m = decl.match(line.strip() if nested else line) if (top or nested) else None
        if not m:
            continue
        k, name, b = m.groups()
        if top:
            outer = name
        elif nested:
            nested_names.setdefault(name, f"{outer}+{name}")
        # the top-level type of the file only (nested types are indented)
        bl = []
        depth = 0
        cur = ""
        for ch in (b or ""):
            if ch == "<": depth += 1
            if ch == ">": depth -= 1
            if ch == "," and depth == 0:
                bl.append(cur.strip()); cur = ""
            else:
                cur += ch
        if cur.strip(): bl.append(cur.strip())
        if name not in bases or f.stem == name or nested:
            bases[name] = bl
            ns_of[name] = ns
            kind[name] = k

def strip(t):
    return re.sub(r"<.*", "", t).split(".")[-1]

def parent(name):
    for b in bases.get(name, []):
        s = strip(b)
        if not re.match(r"^I[A-Z]", s):
            return s
    return None

def ancestors(name):
    seen = []
    while name and name not in seen:
        seen.append(name)
        name = parent(name)
    return seen

COMPONENT_ROOTS = ("BlueprintComponent", "EntityFactComponentDelegate", "EntityFactComponent")
rules = sorted(n for n in bases if kind[n] == "class" and "RulebookEvent" in ancestors(n))
iface = re.compile(r"^(IGlobalRulebookHandler|IInitiatorRulebookHandler|ITargetRulebookHandler)<(\w[\w.]*)>$")
out = collections.defaultdict(set)
for n, bl in bases.items():
    if kind[n] != "class":
        continue
    anc = ancestors(n)
    fact = any(a in ("UnitFact", "EntityFact", "UnitPart", "EntityPart") for a in anc)
    # A fact's component is dispatched with its fact and component names (another kind of `h` record).
    if any(a in COMPONENT_ROOTS or a.endswith("ComponentDelegate") for a in anc):
        continue
    for b in bl:
        m = iface.match(b.strip())
        if not m:
            continue
        which, t = m.group(1), strip(m.group(2))
        if which != "IGlobalRulebookHandler" and not fact:
            continue
        for r in rules:
            if t in ancestors(r):
                out[f"{ns_of[n]}.{nested_names.get(n, n)}"].add(r)

lines = [
    "//! GENERATED by scripts/gen-handler-table.py from the decompiled game code (class declarations'",
    "//! names and bases only); do not edit. The classes that may appear as a rule's singleton handler",
    "//! (an `h` record without a fact or component) and the rules each handles: every class implementing",
    "//! `IGlobalRulebookHandler<T>`, and every fact class implementing `IInitiatorRulebookHandler<T>` or",
    "//! `ITargetRulebookHandler<T>` (`ActivatableAbility`), for each rule that is T or derives from T",
    "//! (the interfaces are contravariant).",
    "",
    "pub(super) const HANDLERS: &[(&str, &[&str])] = &[",
]
for h in sorted(out):
    rs = ", ".join(f'"{r}"' for r in sorted(out[h]))
    lines.append(f'    ("{h}", &[{rs}]),')
lines += [
    "];",
    "",
    "/// Whether the game's code has `handler` handle `rule` (short class names).",
    "pub(super) fn handles(handler: &str, rule: &str) -> bool {",
    "    HANDLERS.iter().any(|(h, rules)| *h == handler && rules.contains(&rule))",
    "}",
    "",
]
pathlib.Path("crates/wr-sim/src/combat/replay/handler_table.rs").write_text("\n".join(lines))
print(len(out), "handler classes,", sum(len(v) for v in out.values()), "pairs,", len(rules), "rules", file=sys.stderr)
